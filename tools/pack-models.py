"""
pack-models.py: bundle the 3D models the village uses into ONE script file.

Why: browsers refuse to load separate .glb/.png files when a page is opened
directly from disk (file://). A <script> tag still works, so we embed the
models (base64) and their textures (data URIs) in assets/model-pack.js.

Usage (from the project root):
    python tools/pack-models.py

Add a model: put its "kit/name" in MODELS below and run the script again.
Sources live in assets/models/<kit>/ (Kenney kits, CC0 licence).
"""
import base64
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "models")
OUT = os.path.join(ROOT, "assets", "model-pack.js")

MODELS = {
    "castle-kit": [
        "tower-square-base", "tower-square-base-color", "tower-square-base-border", "tower-square-mid", "tower-square-mid-windows",
        "tower-square-mid-door", "tower-square-mid-color", "tower-square-top", "tower-square-top-color", "tower-square-top-roof",
        "tower-square-top-roof-high", "tower-square-top-roof-high-windows", "tower-square-top-roof-rounded", "tower-square-roof",
        "tower-hexagon-base", "tower-hexagon-mid", "tower-hexagon-roof", "tower-hexagon-top", "tower-slant-roof",
        "tower-base", "tower-top", "wall", "wall-corner", "wall-pillar", "wall-half", "wall-doorway",
        "gate", "door", "flag", "flag-wide", "flag-banner-long", "flag-banner-short", "flag-pennant", "stairs-stone", "rocks-small",
    ],
    "fantasy-town-kit": [
        "wall-block", "wall", "wall-window-stone", "wall-window-glass", "wall-door", "wall-doorway-round",
        "roof-point", "roof-high-point", "roof-gable", "chimney", "lantern", "fountain-round",
        "banner-red", "banner-green", "fence", "fence-gate", "stall-red", "stall-green", "cart", "pillar-stone",
    ],
    "nature-kit": [
        "tree_oak", "tree_oak_dark", "tree_default", "tree_default_dark", "tree_fat", "tree_pineTallA", "tree_pineRoundA",
        "tree_pineDefaultA", "plant_bushDetailed", "plant_bush", "flower_redA", "flower_yellowA", "flower_purpleA",
        "rock_largeA", "rock_largeB", "rock_tallA", "rock_tallB", "rock_tallC", "stone_tallA", "stone_largeA",
        "tent_detailedOpen", "tent_smallClosed", "campfire_stones", "log_stack", "statue_ring", "statue_obelisk",
        "statue_column", "statue_block", "platform_stone", "stump_round", "mushroom_redGroup", "crop_pumpkin", "grass_large",
    ],
}


def main():
    glb, tex, total = {}, {}, 0
    for kit, names in MODELS.items():
        for name in names:
            path = os.path.join(SRC, kit, name + ".glb")
            if not os.path.isfile(path):
                sys.exit("Missing model: " + path)
            data = open(path, "rb").read()
            total += len(data)
            glb[kit + "/" + name] = base64.b64encode(data).decode("ascii")
        png = os.path.join(SRC, kit, "Textures", "colormap.png")
        if os.path.isfile(png):
            tex[kit + "/Textures/colormap.png"] = "data:image/png;base64," + base64.b64encode(open(png, "rb").read()).decode("ascii")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* AUTO-GENERATED by tools/pack-models.py. Do not edit by hand.\n")
        f.write("   3D models from Kenney (www.kenney.nl), CC0 licence. */\n")
        f.write("window.MODEL_PACK = " + json.dumps({"glb": glb, "tex": tex}, separators=(",", ":")) + ";\n")
    print("Packed %d models (%.2f MB raw) -> %s (%.2f MB)" % (len(glb), total / 1e6, os.path.relpath(OUT, ROOT), os.path.getsize(OUT) / 1e6))


if __name__ == "__main__":
    main()
